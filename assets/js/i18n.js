let currentLang = localStorage.getItem('vmp_lang') || 'pt';

function applyLanguage() {
    // Iterate over all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (vmpTranslations[key] && vmpTranslations[key][currentLang]) {
            element.innerHTML = vmpTranslations[key][currentLang];
        }
    });

    // Update button text
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.textContent = currentLang === 'pt' ? 'EN' : 'PT';
    }
}

function toggleLanguage() {
    currentLang = currentLang === 'pt' ? 'en' : 'pt';
    localStorage.setItem('vmp_lang', currentLang);
    applyLanguage();
}

document.addEventListener('DOMContentLoaded', () => {
    // Inject button into header if not found
    const nav = document.querySelector('.nav');
    if (nav && !document.getElementById('lang-toggle')) {
        const btn = document.createElement('button');
        btn.id = 'lang-toggle';
        btn.className = 'lang-toggle-btn'; // CSS class for styling
        btn.onclick = toggleLanguage;
        nav.appendChild(btn);
    }

    applyLanguage();
});